use std::fmt::Write as _;

use super::*;

const CRATES_IO_GIT: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// A Cargo.lock as Cargo writes it: one `[[package]]` for each of `packages`, a name, a
/// version and a source, or none for a path.
fn cargo_lock(packages: &[(&str, &str, Option<&str>)]) -> String {
    let mut text = "# This file is automatically @generated by Cargo.\nversion = 4\n".to_owned();
    for (name, version, source) in packages {
        let source = source
            .map(|source| format!("source = \"{source}\"\n"))
            .unwrap_or_default();
        write!(
            text,
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n{source}\
             dependencies = [\n \"serde\",\n]\n"
        )
        .unwrap();
    }
    text
}

fn added(change: &Change) -> Vec<(&str, &str, Vec<&str>)> {
    change
        .added
        .iter()
        .map(|added| {
            (
                added.package.name.as_str(),
                added.package.version.as_str(),
                added.replaces.iter().map(String::as_str).collect(),
            )
        })
        .collect()
}

fn skipped(change: &Change) -> Vec<(&str, &str, Elsewhere)> {
    change
        .skipped
        .iter()
        .map(|(package, from)| (package.name.as_str(), package.version.as_str(), *from))
        .collect()
}

#[test]
fn a_crate_added_or_updated_is_new_and_one_removed_or_kept_is_not() {
    let base = cargo_lock(&[
        ("serde", "1.0.228", Some(CRATES_IO_GIT)),
        ("tokio", "1.47.1", Some(CRATES_IO_GIT)),
        ("old", "0.1.0", Some(CRATES_IO_GIT)),
        ("glave", "0.0.0", None),
    ]);
    let head = cargo_lock(&[
        ("serde", "1.0.228", Some(CRATES_IO_GIT)),
        ("tokio", "1.48.0", Some(CRATES_IO_GIT)),
        ("fresh", "2.0.0", Some("sparse+https://index.crates.io/")),
        ("glave", "0.0.0", None),
    ]);
    let change = change(&cargo(&base).unwrap(), &cargo(&head).unwrap());
    assert_eq!(
        added(&change),
        [
            ("fresh", "2.0.0", vec![]),
            ("tokio", "1.48.0", vec!["1.47.1"])
        ]
    );
    assert_eq!(change.skipped, Vec::new());
}

#[test]
fn a_second_version_beside_the_first_replaces_nothing() {
    let base = cargo_lock(&[("syn", "1.0.109", Some(CRATES_IO_GIT))]);
    let head = cargo_lock(&[
        ("syn", "1.0.109", Some(CRATES_IO_GIT)),
        ("syn", "2.0.100", Some(CRATES_IO_GIT)),
    ]);
    let change = change(&cargo(&base).unwrap(), &cargo(&head).unwrap());
    assert_eq!(added(&change), [("syn", "2.0.100", vec![])]);
}

#[test]
fn crates_from_a_path_or_git_are_skipped_and_named() {
    let base = cargo_lock(&[("glave", "0.0.0", None)]);
    let head = cargo_lock(&[
        ("glave", "0.1.0", None),
        (
            "forked",
            "0.3.0",
            Some("git+https://github.com/someone/forked?rev=1a2b#1a2b3c"),
        ),
    ]);
    let change = change(&cargo(&base).unwrap(), &cargo(&head).unwrap());
    assert_eq!(change.added, Vec::new());
    assert_eq!(
        skipped(&change),
        [
            ("forked", "0.3.0", Elsewhere::Git),
            ("glave", "0.1.0", Elsewhere::Path)
        ]
    );
}

#[test]
fn a_crate_from_another_registry_or_a_broken_lockfile_is_refused() {
    let other = cargo_lock(&[("x", "1.0.0", Some("registry+https://example.com/index"))]);
    let err = cargo(&other).unwrap_err();
    assert!(
        err.contains("x 1.0.0 from registry+https://example.com/index"),
        "{err}"
    );
    assert!(cargo("[[package]\n").is_err());
    let unnamed = cargo("[[package]]\nversion = \"1.0.0\"\n").unwrap_err();
    assert!(unnamed.contains("without its name"), "{unnamed}");
    assert_eq!(cargo("").unwrap(), Locked::default());
}

/// A package-lock.json as npm writes it, with `packages` as its entries.
fn package_lock(packages: &Value) -> String {
    serde_json::json!({
        "name": "glave-web",
        "lockfileVersion": 3,
        "requires": true,
        "packages": packages,
    })
    .to_string()
}

fn from_npm(name: &str, version: &str) -> Value {
    serde_json::json!({
        "version": version,
        "resolved": format!("https://registry.npmjs.org/{name}/-/{name}-{version}.tgz"),
        "dev": true,
    })
}

#[test]
fn an_npm_package_added_or_updated_is_new_wherever_it_is_installed() {
    let base = package_lock(&serde_json::json!({
        "": {"name": "glave-web"},
        "node_modules/marked": from_npm("marked", "18.0.13"),
        "node_modules/rxjs": from_npm("rxjs", "7.8.2"),
        "node_modules/gone": from_npm("gone", "1.0.0"),
    }));
    let head = package_lock(&serde_json::json!({
        "": {"name": "glave-web"},
        "node_modules/marked": from_npm("marked", "18.0.14"),
        "node_modules/rxjs": from_npm("rxjs", "7.8.2"),
        "node_modules/@angular/core": from_npm("@angular/core", "22.2.2"),
        // A second copy, nested: one version, dated once.
        "node_modules/a/node_modules/@angular/core": from_npm("@angular/core", "22.2.2"),
        "node_modules/a/node_modules/rxjs": from_npm("rxjs", "7.8.3"),
        // An alias: the package's own name is the one dated.
        "node_modules/hl": {
            "name": "highlight.js",
            "version": "11.12.0",
            "resolved": "https://registry.npmjs.org/highlight.js/-/highlight.js-11.12.0.tgz",
        },
    }));
    let change = change(&npm(&base).unwrap(), &npm(&head).unwrap());
    assert_eq!(
        added(&change),
        [
            ("@angular/core", "22.2.2", vec![]),
            ("highlight.js", "11.12.0", vec![]),
            ("marked", "18.0.14", vec!["18.0.13"]),
            ("rxjs", "7.8.3", vec![]),
        ]
    );
    assert_eq!(change.skipped, Vec::new());
}

#[test]
fn an_npm_package_from_a_path_a_workspace_or_git_is_skipped_and_named() {
    let base = package_lock(&serde_json::json!({"": {"name": "glave-web"}}));
    let head = package_lock(&serde_json::json!({
        "": {"name": "glave-web", "version": "0.0.0"},
        "glaze": {"name": "@glave/glaze", "version": "0.0.0"},
        "node_modules/@glave/glaze": {"resolved": "glaze", "link": true},
        "node_modules/local": {"version": "1.0.0", "resolved": "file:../local"},
        "node_modules/forked": {
            "version": "2.0.0",
            "resolved": "git+ssh://git@github.com/someone/forked.git#1a2b3c",
        },
    }));
    let change = change(&npm(&base).unwrap(), &npm(&head).unwrap());
    assert_eq!(change.added, Vec::new());
    assert_eq!(
        skipped(&change),
        [
            ("@glave/glaze", "0.0.0", Elsewhere::Path),
            ("forked", "2.0.0", Elsewhere::Git),
            ("glave-web", "0.0.0", Elsewhere::Path),
            ("local", "1.0.0", Elsewhere::Path),
        ]
    );
}

#[test]
fn an_npm_package_from_another_registry_or_a_broken_lockfile_is_refused() {
    let other = package_lock(&serde_json::json!({
        "node_modules/x": {"version": "1.0.0", "resolved": "https://example.com/x-1.0.0.tgz"},
    }));
    let err = npm(&other).unwrap_err();
    assert!(
        err.contains("x 1.0.0 from https://example.com/x-1.0.0.tgz"),
        "{err}"
    );
    assert!(npm("{").is_err());
    let old = npm(r#"{"lockfileVersion": 1, "dependencies": {}}"#).unwrap_err();
    assert!(old.contains("lists no `packages`"), "{old}");
}
